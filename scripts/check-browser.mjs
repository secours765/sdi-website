assert.equal(await page.locator('.skip-link').evaluate(el=>el===document.activeElement),true);
await page.keyboard.press('Enter');assert.equal(new URL(page.url()).hash,'#inhalt');
const missing=await page.goto(new URL('nicht-vorhandene-seite/',base).href);assert.equal(missing.status(),404);assert.equal(await page.locator('h1').textContent(),'Hier geht es weiter.');assert.equal(await page.locator('main a').getAttribute('href'),new URL(base).pathname);
