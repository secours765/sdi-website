await page.locator('#reset-filters').click();
assert.equal(await page.locator('.document-row:visible').count(),all);
const download=page.waitForEvent('download');
await page.locator('.document-row a[download]').first().click();
const downloaded=await download;
assert.equal(await downloaded.failure(),null,'local download');
